using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace WavesProtocolGenerator;
internal static class Emitter
{
    internal static Dictionary<string, string> Render(ProtocolModel model)
    {
        var names = model.Messages.Select(m => (m.Name, m.FlatName)).Concat(model.Enums.Select(e => (e.Name, e.FlatName))).ToDictionary(x => x.Name, x => x.FlatName);
        string Type(string t) => names.GetValueOrDefault(t, t);
        var b = new StringBuilder("// Generated by WavesProtocolGenerator. Do not edit.\n// Source: " + model.SourceCommit + "\n// Source SHA256: " + model.SourceHash + "\nsyntax = \"proto3\";\npackage WavesGameData;\noption csharp_namespace = \"Haiyu.ABI.Protocol\";\n\n");
        foreach (var e in model.Enums)
        {
            b.AppendLine($"enum {e.FlatName} {{");
            if (e.Values.Select(v => v.Number).Distinct().Count() != e.Values.Length)
                b.AppendLine("  option allow_alias = true;");
            var values = e.Values.OrderBy(v => v.Number != 0).ToArray();
            if (!values.Any(v => v.Number == 0))
                b.AppendLine($"  {e.FlatName}_GENERATED_UNSPECIFIED = 0;");
            foreach (var v in values)
                b.AppendLine($"  {e.FlatName}_{v.OriginalName ?? v.Name} = {v.Number};");
            b.AppendLine("}\n");
        }

        foreach (var m in model.Messages)
        {
            b.AppendLine("// " + m.Name + " — " + m.Source);
            b.AppendLine($"message {m.FlatName} {{");
            void Field(Field f, string indent)
            {
                var label = f.MapKey != null ? $"map<{Type(f.MapKey)}, {Type(f.Type)}> " : f.Repeated ? "repeated " : f.Optional ? "optional " : "";
                var name = Snake(f.Name);
                var options = f.Repeated && (IsNumeric(f.Type) || model.Enums.Any(e => e.Name == f.Type)) ? $" [packed = {f.Packed.ToString().ToLowerInvariant()}]" : "";
                b.AppendLine($"{indent}{label}{(f.MapKey == null ? Type(f.Type) + " " : "")}{name} = {f.Number}{options};");
            }

            foreach (var f in m.Fields.Where(f => f.Oneof == null))
                Field(f, "  ");
            foreach (var g in m.Fields.Where(f => f.Oneof != null).GroupBy(f => f.Oneof))
            {
                b.AppendLine($"  oneof {Snake(g.Key!)} {{");
                foreach (var f in g)
                    Field(f, "    ");
                b.AppendLine("  }");
            }

            b.AppendLine("}\n");
        }

        var jsonOptions = new JsonSerializerOptions
        {
            PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
            WriteIndented = true
        };
        var schema = JsonSerializer.Serialize(model, jsonOptions) + "\n";
        var proto = b.ToString().Replace("\r\n", "\n").TrimEnd() + "\n";
        var manifest = JsonSerializer.Serialize(new { generatorVersion = 1, model.SourceCommit, model.SourceHash, messageCount = model.Messages.Length, enumCount = model.Enums.Length, fieldCount = model.Messages.Sum(m => m.Fields.Length), registeredCount = model.Ids.Count, syntheticEnumZeros = model.Enums.Where(e => !e.Values.Any(v => v.Number == 0)).Select(e => e.Name).ToArray(), schemaSha256 = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(schema))).ToLowerInvariant(), protoSha256 = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(proto))).ToLowerInvariant() }, jsonOptions) + "\n";
        var ids = new StringBuilder("// Generated by WavesProtocolGenerator. Do not edit.\nnamespace Haiyu.ABI.Protocol;\n\ninternal static class WavesMessageIds\n{\n");
        foreach (var (name, id) in model.IdNames.OrderBy(p => p.Value).ThenBy(p => p.Key, StringComparer.Ordinal))
        {
            if (id < 0 || id > ushort.MaxValue)
                throw new InvalidDataException("msgId outside gateway u16 range: " + id);
            ids.AppendLine($"    internal const ushort {name} = {id};");
        }

        ids.AppendLine("}");
        return new()
        {
            ["WavesGameData.proto"] = proto,
            ["waves-protocol.schema.json"] = schema,
            ["waves-protocol.manifest.json"] = manifest,
            ["WavesMessageIds.cs"] = ids.ToString().Replace("\r\n", "\n")
        };
    }

    private static string Snake(string name) => Regex.Replace(Regex.Replace(name, "([A-Z]+)([A-Z][a-z])", "$1_$2"), "([a-z0-9])([A-Z])", "$1_$2").ToLowerInvariant();
    private static bool IsNumeric(string type) => type is "int32" or "uint32" or "int64" or "uint64" or "sint32" or "sint64" or "fixed32" or "fixed64" or "sfixed32" or "sfixed64" or "bool" or "double" or "float";
}
